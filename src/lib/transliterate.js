// Упрощённая транслитерация кириллицы в латиницу — только для поиска.
//
// Нужна, чтобы запрос «skf» находил «СКФ», а «sepsis» — «сепсис», даже если
// это написание не внесено в tags вручную. Не ГОСТ и не для отображения —
// одна буква кириллицы даёт одну-две латинских, без падежей и особых случаев.

const MAP = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
};

/** Ожидает уже строчный текст. Символы вне карты (латиница, цифры) не трогает. */
export function transliterate(lowerText) {
  let out = '';
  for (const ch of lowerText) out += MAP[ch] ?? ch;
  return out;
}
