// Инструкции по ручной установке — для браузеров, где нативный диалог недоступен.
//
// ВАЖНО про формулировки. Пункты меню у браузеров переезжают от версии к версии,
// поэтому тексты намеренно описывают, ГДЕ искать, а не претендуют на дословный
// путь по кликам. Где установка не поддерживается вовсе — так и написано,
// выдумывать инструкцию хуже, чем честно сказать «нельзя».
//
// Помечено // ПРОВЕРИТЬ — сверить на живом браузере и уточнить.

import { detectBrowser, detectPlatform } from './install.js';

const MENU_DOTS = 'меню браузера (три точки)';

export function getInstallInstructions() {
  const browser = detectBrowser();
  const platform = detectPlatform();

  if (platform === 'ios') {
    if (browser === 'safari') {
      return {
        title: 'Safari на iPhone или iPad',
        steps: [
          'Нажмите «Поделиться» — квадрат со стрелкой вверх внизу экрана.',
          'Пролистайте список вниз и выберите «На экран „Домой“».',
          'Нажмите «Добавить» в правом верхнем углу.',
        ],
      };
    }
    return {
      title: 'iPhone или iPad',
      steps: ['Откройте этот адрес в Safari — на iOS установка возможна только оттуда.'],
      note: 'Ограничение iOS: другие браузеры на iPhone добавить приложение на экран «Домой» не могут.',
    };
  }

  if (browser === 'firefox') {
    return platform === 'android'
      ? {
          title: 'Firefox на Android',
          steps: [`Откройте ${MENU_DOTS}.`, 'Выберите «Добавить на главный экран».'], // ПРОВЕРИТЬ
        }
      : {
          title: 'Firefox на компьютере',
          steps: ['Firefox на компьютере не умеет устанавливать веб-приложения.'],
          note: 'Добавьте страницу в закладки — офлайн-режим работает и без установки. Для установки подойдёт Chrome или Edge.',
        };
  }

  if (browser === 'yandex') {
    return platform === 'android'
      ? {
          title: 'Яндекс.Браузер на Android',
          steps: [`Откройте ${MENU_DOTS}.`, 'Выберите «Добавить на главный экран».'], // ПРОВЕРИТЬ
        }
      : {
          title: 'Яндекс.Браузер на компьютере',
          steps: [
            'Откройте меню браузера.',
            'Найдите пункт установки приложения — он может называться «Установить приложение» или «Создать ярлык».',
          ], // ПРОВЕРИТЬ
          note: 'В Яндекс.Браузере на компьютере установка работает нестабильно. Если пункта нет — откройте адрес в Chrome или Edge.',
        };
  }

  if (platform === 'android') {
    return {
      title: 'Chrome на Android',
      steps: [`Откройте ${MENU_DOTS}.`, 'Выберите «Установить приложение» или «Добавить на главный экран».'],
    };
  }

  if (browser === 'safari') {
    return {
      title: 'Safari на Mac',
      steps: ['Меню «Файл» → «Добавить в Dock».'],
      note: 'Нужна macOS Sonoma или новее. В более старых версиях установка недоступна.',
    };
  }

  // Chrome, Edge и прочие Chromium на компьютере
  return {
    title: browser === 'edge' ? 'Edge на компьютере' : 'Chrome на компьютере',
    steps: [
      'Нажмите значок установки в правой части адресной строки.',
      'Если значка нет — откройте меню браузера и найдите пункт «Установить приложение».',
    ],
  };
}
