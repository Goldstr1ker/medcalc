// Клиренс креатинина по формуле Кокрофта–Голта.
// CrCl = [(140 - возраст) × масса(кг) × (0,85 если жен.)] / (72 × Scr(мг/дл))
//
// В отличие от СКФ по CKD-EPI, результат не нормирован на площадь поверхности
// тела — это абсолютный клиренс, исторически применяемый для дозирования ЛС.

