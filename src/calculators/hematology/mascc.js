// Индекс MASCC — риск осложнений при фебрильной нейтропении.
// Балл ≥ 21 выделяет пациентов низкого риска, которым возможно
// пероральное и/или амбулаторное лечение.

import { SYSTEMS } from '../../lib/systems.js';
import { tally } from '../_shared/scoring.js';

const BURDEN = ['Симптомов нет или лёгкие', 'Умеренные симптомы', 'Тяжёлые симптомы'];
const BURDEN_PTS = [5, 3, 0];

/** @type {import('../../lib/types.js').Calculator} */
export default {
  id: 'mascc',
  name: 'Индекс MASCC (фебрильная нейтропения)',
  shortName: 'MASCC',
  system: SYSTEMS.HEMATOLOGY,
  tags: ['mascc', 'маскк', 'фебрильная нейтропения', 'нейтропеническая лихорадка', 'онкология', 'химиотерапия'],
  description:
    'Стратификация риска тяжёлых осложнений у онкологического пациента с фебрильной нейтропенией. Балл ≥ 21 — низкий риск.',

  inputs: [
    { id: 'burden', label: 'Тяжесть проявлений фебрильной нейтропении', type: 'select', options: BURDEN },
    { id: 'noHypotension', label: 'Систолическое АД > 90 мм рт. ст. (гипотензии нет)', type: 'boolean' },
    { id: 'noCopd', label: 'Хронической обструктивной болезни лёгких нет', type: 'boolean' },
    {
      id: 'tumorType',
      label: 'Солидная опухоль либо гемобластоз без предшествующей грибковой инфекции',
      type: 'boolean',
    },
    { id: 'noDehydration', label: 'Дегидратации, требующей парентеральной инфузии, нет', type: 'boolean' },
    { id: 'outpatient', label: 'На момент появления лихорадки — амбулаторный пациент', type: 'boolean' },
    { id: 'age', label: 'Возраст', type: 'number', unit: 'лет', min: 16, max: 100 },
  ],

  calculate({ burden, noHypotension, noCopd, tumorType, noDehydration, outpatient, age }) {
    const burdenPts = BURDEN_PTS[BURDEN.indexOf(burden)];
    return tally([
      [burdenPts > 0, `Тяжесть проявлений: ${burden.toLowerCase()}`, burdenPts],
      [noHypotension, 'Гипотензии нет', 5],
      [noCopd, 'ХОБЛ нет', 4],
      [tumorType, 'Солидная опухоль / гемобластоз без грибковой инфекции', 4],
      [noDehydration, 'Дегидратации нет', 3],
      [outpatient, 'Амбулаторный статус на момент лихорадки', 3],
      [age < 60, 'Возраст < 60 лет', 2],
    ]);
  },

  result: {
    type: 'score',
    max: 26,
    bands: [
      { id: 'high', label: '< 21 — высокий риск осложнений', min: 0, color: 'red' },
      { id: 'low', label: '≥ 21 — низкий риск осложнений', min: 21, color: 'green' },
    ],
  },

  interpretation: {
    high: 'Балл < 21 — высокий риск тяжёлых осложнений фебрильной нейтропении.',
    low: 'Балл ≥ 21 — низкий риск тяжёлых осложнений. Такие пациенты — кандидаты на пероральную антибактериальную терапию и, при соблюдении условий, амбулаторное лечение.',
  },

  guidance: {
    high: {
      source: 'Klastersky J, et al. J Clin Oncol 2000; КР «Фебрильная нейтропения»; NCCN, ESMO',
      points: [
        'Госпитализация, внутривенная эмпирическая антибактериальная терапия широкого спектра с антисинегнойной активностью (пиперациллин/тазобактам, цефепим, карбапенем) в первый час.',
        'Посевы крови (из периферической вены и из центрального катетера), поиск очага инфекции.',
        'Оценка показаний к добавлению ванкомицина (катетер-ассоциированная инфекция, тяжёлый мукозит, гемодинамическая нестабильность, колонизация резистентной флорой) и противогрибковой терапии при затяжной лихорадке.',
      ],
    },
    low: {
      source: 'Klastersky J, et al. J Clin Oncol 2000; NCCN, ESMO, IDSA',
      points: [
        'Возможна пероральная терапия (амоксициллин/клавуланат + ципрофлоксацин) при отсутствии профилактического приёма фторхинолонов.',
        'Амбулаторное лечение допустимо только при надёжном наблюдении, доступности стационара в пределах часа, отсутствии тяжёлой сопутствующей патологии и согласии пациента.',
        'Обязателен осмотр через 24–72 часа; при сохранении лихорадки или ухудшении — госпитализация и переход на внутривенные антибиотики.',
      ],
    },
  },

  caveats: [
    'Индекс валидирован для взрослых; у детей применяются другие правила (напр. правило Rondinelli, шкала SPOG).',
    'Низкий балл MASCC не отменяет клинической оценки: при явных признаках сепсиса, органной дисфункции или тяжёлого мукозита пациент ведётся как высокий риск независимо от суммы.',
    'Пункт «тяжесть проявлений» оценивается субъективно; при сомнении между «нет/лёгкие» и «умеренные» выбирают более тяжёлый вариант.',
    'Пункты «возраст < 60» и «тяжесть проявлений» не суммируются с другими возрастными или симптоматическими категориями — каждый учитывается один раз.',
  ],

  examples: [
    {
      note: 'Тяжёлые симптомы (0) + гипотензия + ХОБЛ + дегидратация, стационарный пациент 70 лет — 4 балла (только «тип опухоли»)',
      inputs: {
        burden: BURDEN[2],
        tumorType: true,
        age: 70,
      },
      expect: { value: 4, band: 'high' },
    },
    {
      note: 'Умеренные симптомы (3) + нет гипотензии (5) + нет ХОБЛ (4) + тип опухоли (4) + нет дегидратации (3) — 19, ещё высокий риск',
      inputs: {
        burden: BURDEN[1],
        noHypotension: true,
        noCopd: true,
        tumorType: true,
        noDehydration: true,
        age: 65,
      },
      expect: { value: 19, band: 'high' },
    },
    {
      note: 'Лёгкие симптомы (5) + нет гипотензии (5) + нет ХОБЛ (4) + тип опухоли (4) + нет дегидратации (3) + амбулаторный (3) + возраст < 60 (2) — максимум 26',
      inputs: {
        burden: BURDEN[0],
        noHypotension: true,
        noCopd: true,
        tumorType: true,
        noDehydration: true,
        outpatient: true,
        age: 45,
      },
      expect: { value: 26, band: 'low' },
    },
    {
      note: 'Умеренные симптомы (3) + нет гипотензии (5) + нет ХОБЛ (4) + тип опухоли (4) + нет дегидратации (3) + возраст < 60 (2) — ровно 21, низкий риск',
      inputs: {
        burden: BURDEN[1],
        noHypotension: true,
        noCopd: true,
        tumorType: true,
        noDehydration: true,
        age: 50,
      },
      expect: { value: 21, band: 'low' },
    },
  ],

  references: [
    'Klastersky J, Paesmans M, Rubenstein EB, et al. The Multinational Association for Supportive Care in Cancer risk index. J Clin Oncol. 2000;18(16):3038–3051.',
  ],
  updated: '2026-09-07',
  version: '1.0',
};
