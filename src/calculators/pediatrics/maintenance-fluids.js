  inputs: [{ id: 'weight', label: 'Масса тела', type: 'number', unit: 'кг', min: 1, max: 150 }],

  calculate({ weight }) {
    let rate;
    if (weight <= 10) rate = weight * 4;
    else if (weight <= 20) rate = 10 * 4 + (weight - 10) * 2;
    else rate = 10 * 4 + 10 * 2 + (weight - 20) * 1;

    return {
      value: rate,
      unit: 'мл/ч',
      decimals: 0,
      details: [{ label: 'Суточный объём', value: rate * 24, unit: 'мл' }],
    };
  },

