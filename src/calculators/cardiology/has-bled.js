  description:
    'Оценка риска кровотечения на фоне антикоагулянтной терапии при фибрилляции предсердий — используется для выявления модифицируемых факторов, а не для отказа от антикоагуляции.',

  inputs: [
    { id: 'age', label: 'Возраст', type: 'number', unit: 'лет', min: 0, max: 120 },
    { id: 'htn', label: 'Артериальная гипертензия (САД > 160 мм рт. ст.)', type: 'boolean' },
    { id: 'renal', label: 'Нарушение функции почек (диализ, трансплантация, креатинин > 200 мкмоль/л)', type: 'boolean' },
    { id: 'hepatic', label: 'Нарушение функции печени (цирроз, билирубин > 2N, АСТ/АЛТ/ЩФ > 3N)', type: 'boolean' },
    { id: 'stroke', label: 'Инсульт в анамнезе', type: 'boolean' },
    { id: 'bleeding', label: 'Кровотечение в анамнезе или предрасположенность к нему', type: 'boolean' },
    { id: 'labileInr', label: 'Лабильное МНО (на варфарине, TTR < 60%)', type: 'boolean' },
    { id: 'drugs', label: 'Антиагреганты или НПВП', type: 'boolean' },
    { id: 'alcohol', label: 'Алкоголь ≥ 8 порций в неделю', type: 'boolean' },
  ],

  calculate({ age, htn, renal, hepatic, stroke, bleeding, labileInr, drugs, alcohol }) {
    const breakdown = [];
    let score = 0;
    const add = (cond, label) => {
      if (cond) {
        score += 1;
        breakdown.push({ label, points: 1 });
      }
    };
    add(htn, 'Артериальная гипертензия');
    add(renal, 'Нарушение функции почек');
    add(hepatic, 'Нарушение функции печени');
    add(stroke, 'Инсульт в анамнезе');
    add(bleeding, 'Кровотечение в анамнезе/предрасположенность');
    add(labileInr, 'Лабильное МНО');
    add(age >= 65, 'Возраст ≥ 65 лет');
    add(drugs, 'Антиагреганты/НПВП');
    add(alcohol, 'Злоупотребление алкоголем');
    return { value: score, decimals: 0, breakdown };
  },

  result: {
    type: 'score',
    max: 9,
    bands: [
      { id: 'low', label: 'Низкий риск (0–2)', min: 0, color: 'green' },
      { id: 'high', label: 'Высокий риск (≥ 3)', min: 3, color: 'red', risk: 'требует более частого контроля' },
    ],
  },

  interpretation: {
    low: 'HAS-BLED 0–2 — низкий расчётный риск кровотечения на антикоагулянтах.',
    high: 'HAS-BLED ≥ 3 — повышенный риск кровотечения. Это сигнал для более пристального наблюдения и коррекции модифицируемых факторов, а не автоматическое основание для отказа от антикоагулянтной терапии.',
  },

  guidance: {
    low: {
      source: 'ESC 2020 «Фибрилляция предсердий»',
      points: ['Стандартная периодичность контроля при антикоагулянтной терапии.'],
    },
    high: {
      source: 'ESC 2020 «Фибрилляция предсердий»; Pisters R, et al. Chest 2010',
      points: [
        'Высокий HAS-BLED сам по себе не повод отменять или не назначать ОАК, особенно при высоком CHA₂DS₂-VASc — риск инсульта без антикоагуляции обычно превышает риск кровотечения.',
        'Скорректировать модифицируемые факторы: целевое АД, отмена НПВП/антиагрегантов без строгих показаний, ограничение алкоголя, стабилизация МНО (или переход на ПОАК).',
        'Более частый клинический и лабораторный контроль, ранняя оценка при признаках кровотечения.',
        'При выборе между ОАК — у пациентов с повышенным риском кровотечения ПОАК в целом безопаснее варфарина.',
      ],
    },
  },

  caveats: [
    'HAS-BLED и CHA₂DS₂-VASc используют перекрывающиеся факторы риска — пациенты с высоким риском кровотечения часто одновременно имеют высокий риск инсульта.',
    'Шкала не должна использоваться как единственное основание для отказа от антикоагулянтной терапии при показаниях к ней.',
  ],

  examples: [
    {
      note: '50 лет, факторов нет — 0 баллов',
      inputs: { age: 50 },
      expect: { value: 0, band: 'low' },
    },
    {
      note: '66 лет с нарушением функции почек: 1 (почки) + 1 (возраст ≥65)',
      inputs: { age: 66, renal: true },
      expect: { value: 2, band: 'low' },
    },
    {
      note: '70 лет, АГ + кровотечение в анамнезе + НПВП: 1+1+1 + 1 (возраст)',
      inputs: { age: 70, htn: true, bleeding: true, drugs: true },
      expect: { value: 4, band: 'high' },
    },
  ],

  references: [
    'Pisters R, et al. A novel user-friendly score (HAS-BLED) to assess 1-year risk of major bleeding. Chest. 2010;138(5):1093–1100.',
    'Hindricks G, et al. 2020 ESC Guidelines for the diagnosis and management of atrial fibrillation. Eur Heart J. 2021;42(5):373–498.',
  ],
  updated: '2026-09-04',
