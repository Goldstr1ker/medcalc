  calculate({ bilirubin, creatinine, inr, sodium, dialysis }) {
    const bili = Math.max(bilirubin, 1);
    const inrV = Math.max(inr, 1);
    let cr = dialysis ? 4 : Math.max(creatinine, 1);
    cr = Math.min(cr, 4);

    let meld = 3.78 * Math.log(bili) + 11.2 * Math.log(inrV) + 9.57 * Math.log(cr) + 6.43;
    meld = Math.min(Math.max(Math.round(meld), 6), 40);

    const na = Math.min(Math.max(sodium, 125), 137);
    let meldNa = meld;
    if (meld > 11) {
      meldNa = meld + 1.32 * (137 - na) - 0.033 * meld * (137 - na);
      meldNa = Math.min(Math.max(Math.round(meldNa), 6), 40);
    }

    return {
      value: meldNa,
      unit: 'баллов',
      decimals: 0,
      details: [{ label: 'MELD без поправки на натрий', value: meld, unit: 'баллов' }],
    };
  },

